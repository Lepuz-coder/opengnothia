#!/usr/bin/env node
// Build-time migration codegen (Open Question 3, option c): reads
// packages/shared/migrations/*.sql — the single source of truth shared with
// the desktop app's include_str! embedding — and emits src/generated/
// migrations.ts for runMigrations. Runs automatically before `pnpm start`;
// the output is committed so type-checking works without a generate step.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const migrationsDir = path.resolve(here, "../../../packages/shared/migrations");
const outFile = path.resolve(here, "../src/generated/migrations.ts");

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

let previousVersion = 0;
const entries = files.map((file) => {
  const match = /^(\d+)_/.exec(file);
  if (!match) throw new Error(`cannot parse migration version from ${file}`);
  const version = Number(match[1]);
  if (version <= previousVersion) {
    throw new Error(`migration versions must be strictly increasing; ${file} follows ${previousVersion}`);
  }
  previousVersion = version;
  return { version, file, sql: readFileSync(path.join(migrationsDir, file), "utf8") };
});

const body = entries
  .map((e) => `  // ${e.file}\n  { version: ${e.version}, sql: ${JSON.stringify(e.sql)} },`)
  .join("\n");

const output = `// AUTO-GENERATED by scripts/generate-migrations.mjs — do not edit by hand.
// Source of truth: packages/shared/migrations/*.sql. Regenerate with
// \`pnpm generate:migrations\` (also runs automatically before \`pnpm start\`).
import type { MigrationDef } from "@opengnothia/shared/db";

export const MIGRATIONS: MigrationDef[] = [
${body}
];
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, output);
console.log(`generated ${path.relative(process.cwd(), outFile)} from ${entries.length} migrations`);
